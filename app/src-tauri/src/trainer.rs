//! Trainer generator (like Cheat Engine's "Create generic trainer Lua script from table"):
//! a Lua script for the table's own Lua script that builds a form with one toggle per chosen
//! entry and registers their hotkeys. It runs inside HeapHook; standalone .exe trainers are
//! not built.
use std::collections::HashSet;

use serde::Deserialize;

use crate::commands::{App, R};

/// Marks the generated block inside the table script, so regenerating replaces it.
pub const BEGIN: &str = "-- BEGIN HEAPHOOK TRAINER";
pub const END: &str = "-- END HEAPHOOK TRAINER";

#[derive(Debug, Clone, Default, Deserialize)]
#[serde(default)]
pub struct TrainerReq {
    pub title: String,
    /// Text shown above the toggles (empty = none).
    pub about: String,
    pub entries: Vec<TrainerItem>,
    /// Beep when a trainer hotkey toggles an entry.
    pub beep: bool,
    /// Show each toggle's key combination next to its label.
    pub show_keys: bool,
}

#[derive(Debug, Clone, Default, Deserialize)]
#[serde(default)]
pub struct TrainerItem {
    pub id: i64,
    /// Label on the form; empty = the entry's description.
    pub label: String,
    /// CE virtual-key codes; empty = no hotkey.
    pub keys: Vec<u32>,
}

/// A Lua string literal.
fn lua_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 32 => o.push_str(&format!("\\{:03}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

impl App {
    /// The trainer script for `req` (between [`BEGIN`] and [`END`]).
    pub fn trainer_script(&self, req: &TrainerReq) -> R<String> {
        if req.entries.is_empty() {
            return Err("pick at least one table entry for the trainer".into());
        }
        let mut items = Vec::new();
        for it in &req.entries {
            let e = self.x.live.entry(it.id).ok_or_else(|| format!("no table entry {}", it.id))?;
            let mut keys = it.keys.clone();
            keys.sort_unstable();
            keys.dedup();
            // The entry's own hotkey with these keys already toggles it: the trainer then
            // only shows the keys (registering them again would toggle twice per press).
            let owned = !keys.is_empty()
                && !e.hotkeys.iter().any(|h| {
                    let mut k = h.keys.clone();
                    k.sort_unstable();
                    k == keys && h.action.starts_with("Toggle Activation")
                });
            let label = if it.label.trim().is_empty() { e.description.clone() } else { it.label.trim().to_string() };
            let keys_lua = keys.iter().map(u32::to_string).collect::<Vec<_>>().join(", ");
            items.push(format!("    {{ id = {}, label = {}, keys = {{ {keys_lua} }}, own = {owned} }},", it.id, lua_str(&label)));
        }
        let mut seen = HashSet::new();
        if req.entries.iter().any(|i| !seen.insert(i.id)) {
            return Err("an entry is in the trainer twice".into());
        }
        let title = if req.title.trim().is_empty() { "Trainer" } else { req.title.trim() };
        Ok(format!(
            r#"{BEGIN}
-- Generated by HeapHook's trainer generator. It runs inside HeapHook (as the table's Lua
-- script); HeapHook does not build standalone .exe trainers. Regenerating replaces this block.
do
  local items = {{
{items}
  }}
  local title, about, beepOn, showKeys = {title}, {about}, {beep}, {show_keys}
  local al = getAddressList()
  if HHTrainer and HHTrainer.form then pcall(function() HHTrainer.form.destroy() end) end
  if HHTrainer and HHTrainer.hotkeys then for _, h in ipairs(HHTrainer.hotkeys) do pcall(function() h.destroy() end) end end
  HHTrainer = {{ hotkeys = {{}}, boxes = {{}} }}
  local f = createForm(false)
  HHTrainer.form = f
  f.Caption = title
  f.Position = poScreenCenter
  f.Width = 320
  local y = 12
  if about ~= '' then
    local l = createLabel(f)
    l.Caption, l.Left, l.Top, l.Width = about, 12, y, 296
    y = y + 26
  end
  local function active(id)
    local r = al.getMemoryRecordByID(id)
    return r ~= nil and r.Active
  end
  for i, it in ipairs(items) do
    local cb = createCheckBox(f)
    cb.Left, cb.Top, cb.Width, cb.Height = 12, y, 296, 22
    local keys = (#it.keys > 0 and showKeys) and ('   ' .. convertKeyComboToString(it.keys)) or ''
    cb.Caption = it.label .. keys
    cb.Checked = active(it.id)
    cb.OnClick = function()
      local r = al.getMemoryRecordByID(it.id)
      if r and r.Active ~= cb.Checked then r.Active = cb.Checked end
      cb.Checked = active(it.id)
    end
    HHTrainer.boxes[i] = cb
    if it.own then
      HHTrainer.hotkeys[#HHTrainer.hotkeys + 1] = createHotkey(function()
        local r = al.getMemoryRecordByID(it.id)
        if r then r.Active = not r.Active end
        cb.Checked = active(it.id)
        if beepOn then beep() end
      end, it.keys)
    end
    y = y + 26
  end
  f.Height = y + 10
  -- Keep the boxes in step with the table (entry hotkeys, the table view, scripts).
  local t = createTimer(f)
  t.Interval = 250
  t.OnTimer = function()
    for i, it in ipairs(items) do
      local a = active(it.id)
      if HHTrainer.boxes[i].Checked ~= a then HHTrainer.boxes[i].Checked = a end
    end
  end
  f.OnClose = function() return caHide end
  f.show()
end
{END}
"#,
            items = items.join("\n"),
            title = lua_str(title),
            about = lua_str(req.about.trim()),
            beep = req.beep,
            show_keys = req.show_keys,
        ))
    }
}

